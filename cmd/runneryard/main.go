package main

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"os"
	"os/signal"
	"syscall"

	"github.com/gwendall/runneryard/controller"
	"github.com/gwendall/runneryard/githubapp"
)

var (
	version   = "dev"
	commitSHA = "unknown"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(args []string) error {
	command := "serve"
	if len(args) > 0 {
		command = args[0]
		args = args[1:]
	}
	switch command {
	case "serve":
		return serve()
	case "init":
		return runInit(args)
	case "doctor":
		return runDoctor(args)
	case "auth":
		return runAuth(args)
	case "route":
		return runRoute(args)
	case "status":
		return runStatus(args)
	case "budget":
		return runBudget(args)
	case "lint-workflows":
		return runLintWorkflows(args)
	case "host":
		return runHost(args)
	case "version", "--version", "-v":
		fmt.Printf("runneryard %s (%s)\n", version, commitSHA)
		return nil
	case "help", "--help", "-h":
		printHelp()
		return nil
	default:
		return fmt.Errorf("unknown command %q; run runneryard help", command)
	}
}

func serve() error {
	cfg, err := loadConfig()
	if err != nil {
		return err
	}
	logger := slog.New(slog.NewJSONHandler(os.Stdout, &slog.HandlerOptions{Level: cfg.LogLevel}))
	if os.Getenv("CONTROLLER_ID") == "" {
		logger.Warn("CONTROLLER_ID is not set; defaulting to the scale set name, which another fleet sharing this worker app would also use. Set the value generated by runneryard init.", "controller_id", cfg.ControllerID)
	}
	github, err := cfg.githubClient()
	if err != nil {
		return fmt.Errorf("create GitHub adapter: %w", err)
	}
	compute, err := cfg.compute(logger)
	if err != nil {
		return fmt.Errorf("create compute adapter: %w", err)
	}
	fleet, err := controller.New(cfg.controllerConfig(logger), github, compute)
	if err != nil {
		return fmt.Errorf("create controller: %w", err)
	}

	signalCtx, cancel := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer cancel()
	ctx, stop := context.WithCancelCause(signalCtx)
	defer stop(nil)
	if cfg.Pools != nil {
		if err := cfg.checkPoolTrust(ctx, githubapp.API{}); err != nil {
			return err
		}
		go cfg.watchPoolTrust(ctx, githubapp.API{}, poolTrustInterval, stop, logger)
	}
	if err := fleet.Run(ctx); err != nil && !errors.Is(err, context.Canceled) {
		return fmt.Errorf("controller stopped: %w", err)
	}
	if cause := context.Cause(ctx); cause != nil && !errors.Is(cause, context.Canceled) {
		return fmt.Errorf("controller stopped: %w", cause)
	}
	return nil
}

func printHelp() {
	fmt.Print(`RunnerYard starts one isolated GitHub Actions runner per job.

Usage:
  runneryard init [flags]     Create a safe starter configuration
  runneryard doctor [flags]   Check credentials, isolation, and tooling
  runneryard auth github      Create or import a dedicated GitHub App
  runneryard route            Inspect or switch Linux runner routing
  runneryard status           Read the controller fleet snapshot
  runneryard budget init      Initialize the durable usage ledger once
  runneryard budget estimate  Size RUNNER_USAGE_BUDGET and the Fly or Hetzner bill from a workload
  runneryard lint-workflows   Say what a repository's workflows will cost on a fleet
  runneryard host             Run or install the agent of a pool host
  runneryard serve            Run the fleet controller (default)
  runneryard version          Print version information

Run "runneryard <command> --help" for command-specific options.
`)
}
